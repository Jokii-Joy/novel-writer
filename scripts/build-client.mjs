#!/usr/bin/env node
// Concatenate client/src/*.js into the single classic script the Harness module loader expects.
// Every part except 00-boot.js / 99-end.js must be one `;(() => { ... })();` IIFE writing to `NW`.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const srcDir = join(root, 'client', 'src');
const outFile = join(root, 'client', 'client.js');

const files = readdirSync(srcDir)
  .filter((name) => name.endsWith('.js'))
  .sort();

if (!files.includes('00-boot.js') || !files.includes('99-end.js')) {
  console.error('build-client: 00-boot.js and 99-end.js are required');
  process.exit(1);
}

const parts = files.map((name) => {
  const text = readFileSync(join(srcDir, name), 'utf8');
  return `\n/* ==== ${name} ==== */\n${text.trimEnd()}\n`;
});

const banner =
  '/* @local/novel-writer — generated by scripts/build-client.mjs. Do not edit by hand. */\n';
const body = banner + parts.join('');

writeFileSync(outFile, body, 'utf8');
console.log(`build-client: wrote ${outFile} (${files.length} parts, ${body.length} bytes)`);

// Parsing and loading are different things: a stray backtick inside a CSS
// template literal parses fine and then blows up the moment the factory runs,
// which takes the whole panel out of the UI. Gate the build on the load check.
const check = spawnSync(process.execPath, [join(here, 'verify-client-load.mjs'), outFile], {
  stdio: 'inherit',
});
if (check.status !== 0) {
  console.error('build-client: the generated bundle does not load — fix the client half before shipping');
  process.exit(1);
}

// A parsed, loadable bundle can still be wrong at runtime: an async helper tested
// as a boolean reads fine and then disables a whole feature (see the guard's own
// header for the R79 case). Cheap to check, so every build runs it.
const guards = spawnSync(process.execPath, [join(here, 'verify-async-guards.mjs')], {
  stdio: 'inherit',
});
if (guards.status !== 0) {
  console.error('build-client: the client half uses an async helper as a boolean — fix it before shipping');
  process.exit(1);
}

// The restore planner decides which object stores a backup may overwrite. A
// wrong answer here deletes work the writer cannot get back, and the decision
// table is pure (no IndexedDB), so it is cheap to pin on every build.
const restore = spawnSync(process.execPath, [join(here, 'verify-restore.mjs')], {
  stdio: 'inherit',
});
if (restore.status !== 0) {
  console.error('build-client: the restore planner regressed — a backup could now wipe a store it does not carry');
  process.exit(1);
}

// The password verifier is mirrored to DSH_HOME so a reinstall of the host does
// not lock the writer out of their own ciphertext. The walk-through runs in a
// fake localStorage, so it is fast and needs no browser.
const recovery = spawnSync(process.execPath, [join(here, 'verify-crypto-recovery.mjs')], {
  stdio: 'inherit',
});
if (recovery.status !== 0) {
  console.error('build-client: password recovery from the host copy regressed');
  process.exit(1);
}

// Mark emphasis is design, but it is also a contract: two kinds of annotation
// must not collapse into the same underlined look, and a tint that vanishes on
// one of the five papers is a bug the writer sees every day. The palette table
// is static, so gate the build on the measured contrast.
const highlight = spawnSync(process.execPath, [join(here, 'verify-highlight-style.mjs')], {
  stdio: 'inherit',
});
if (highlight.status !== 0) {
  console.error('build-client: a highlight/comment tint no longer stands out from its paper');
  process.exit(1);
}

// R85: pasted advice becomes ordinary cards, so the parser is the only place
// that can mis-place a highlight. It is a pure IIFE and runs in plain Node.
const paste = spawnSync(process.execPath, [join(here, 'verify-advice-paste.mjs')], {
  stdio: 'inherit',
});
if (paste.status !== 0) {
  console.error('build-client: the paste-import parser regressed');
  process.exit(1);
}

// R101: the module loader only proves the factory runs; the panel can still
// throw on its first render (that is exactly how R100 shipped a blank screen —
// a dependency array read a `const` declared further down). Render App and
// Welcome once with a tiny React stand-in so that class of crash fails the build.
const smoke = spawnSync(process.execPath, [join(here, 'smoke-app-render.mjs')], {
  stdio: 'inherit',
});
if (smoke.status !== 0) {
  console.error('build-client: the panel crashes on its first render');
  process.exit(1);
}
